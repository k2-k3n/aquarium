"""Serialize the Aquarium RGB565 title sequence for the device's boot player."""
from itertools import groupby
from math import pi, sin
from pathlib import Path
import struct
import zlib

ROOT = Path(__file__).resolve().parent.parent
W, H = 320, 172
INK = 0x0063  # Same starting color as the app's scene fade.

def channels(color):
    return ((color >> 11) * 255 // 31, ((color >> 5) & 63) * 255 // 63, (color & 31) * 255 // 31)

def frame(phase):
    result = [INK] * (W * H)
    strength = sin(pi * phase) ** 2
    # Broad, dim water light. Its edge softens toward the lower left.
    for y in range(96):
        glow = strength * (1 - y / 96)
        edge = 176 + y + round(24 * phase)
        for band in range(3):
            x = edge + band * 26
            if x >= W:
                break
            green = round((1 + band) * glow)
            blue = round((2 + band) * glow)
            color = (3 + green) << 5 | (3 + blue)
            end = min(W, x + 26) if band < 2 else W
            result[y * W + x:y * W + end] = [color] * (end - x)
    return result

def write_png_animation(path, frames):
    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data))
    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">2I5B", W, H, 8, 2, 0, 0, 0))
    png += chunk(b"acTL", struct.pack(">2I", len(frames), 0))
    sequence = 0
    for index, (delay, colors) in enumerate(frames):
        png += chunk(b"fcTL", struct.pack(">5I2H2B", sequence, W, H, 0, 0, delay, 1000, 0, 0))
        sequence += 1
        raw = b"".join(b"\0" + bytes(c for col in colors[y:y + W] for c in channels(col))
                       for y in range(0, W * H, W))
        compressed = zlib.compress(raw)
        if index == 0:
            png += chunk(b"IDAT", compressed)
        else:
            png += chunk(b"fdAT", struct.pack(">I", sequence) + compressed)
            sequence += 1
    path.write_bytes(png + chunk(b"IEND", b""))

frames = [(32, frame(i / 18)) for i in range(19)]
payload = bytearray()
for delay, colors in frames:
    runs = [(sum(1 for _ in group), color) for color, group in groupby(colors)]
    payload += struct.pack("<II", delay, len(runs))
    for length, color in runs:
        payload += struct.pack("<HH", length, color)
duration = sum(delay for delay, _ in frames)
data = struct.pack("<4s7I", b"RSP1", len(payload) + 32, zlib.crc32(payload),
                   duration, W, H, len(frames), 0) + payload
if len(data) > 24576:
    raise SystemExit(f"Splash exceeds 24 KiB: {len(data)} bytes")
rows = [", ".join(str(byte) for byte in data[i:i+24]) for i in range(0, len(data), 24)]
(ROOT / "src/aquarium_splash.h").write_text(
    "// Generated by tools/make_splash.py.\n#pragma once\n#include <stdint.h>\n"
    + "alignas(4) static const uint8_t kAquariumSplash[] = {\n    "
    + ",\n    ".join(rows) + "\n};\n")
(ROOT / "build").mkdir(exist_ok=True)
(ROOT / "build/aquarium-startup.rsp").write_bytes(data)
write_png_animation(ROOT / "assets/aquarium-startup.png", frames)
print(f"{len(data)} bytes, {len(frames)} frames, {duration} ms")
